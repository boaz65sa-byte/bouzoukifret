/* ============================================================
   ספריית תרגילים
   קורסים: 0 = D (גבוה) · 1 = A · 2 = F · 3 = C (נמוך)
   sub: תאי רשת לפעמה · len: אורך בתאי רשת
   כיוון: 'D'/'U' = מודגש · 'd'/'u' = רגיל
   ============================================================ */
function _n(c, f, d, len = 1) { return { c, f, d, len }; }
function _rest(len = 1) { return { rest: true, len }; }
function _alt(seq, startDown = true) {
  /* seq: מערך [course, fret, len?] — פנייה מתחלפת אוטומטית */
  return seq.map((s, i) => _n(s[0], s[1], (i % 2 === 0) === startDown ? 'd' : 'u', s[2] || 1));
}
function _rep(arr, times) {
  const out = [];
  for (let i = 0; i < times; i++) out.push(...arr.map(o => ({ ...o })));
  return out;
}

